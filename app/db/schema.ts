/*===== Consent =====*/
// What a person agreed to, exactly which wording, and when (docs/app-spec.md, F1 and F13): the site rules, and later a
// dog's public logbook. A row says the person accepted version V of the text at a time; withdrawing sets `revoked_at`
// and the row stays, so the record of what was agreed and when is never lost. Rows are never deleted.

export const consent = pgTable(
  "consent",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    /** What was agreed to, as plain text. Allowed values live in `app/orpc/consent/constants.ts`. */
    kind: text("kind").notNull(),
    /** The wording's version, so the record names the exact text that was accepted. */
    version: text("version").notNull(),
    /** The dog it is about, for a consent that is given per dog (a public logbook); null for the account's own. */
    dogId: uuid("dog_id").references(() => dog.id, { onDelete: "restrict" }),
    acceptedAt: timestamp("accepted_at").notNull().defaultNow(),
    /** When the person took it back; null while it stands. */
    revokedAt: timestamp("revoked_at"),
  },
  (table) => [
    index("consent_user_id_kind_idx").on(table.userId, table.kind),
    // One standing consent per person, kind and version (and dog, for the per-dog kinds). Held by the database, so a
    // double click or two tabs can't record two.
    uniqueIndex("consent_account_standing_idx")
      .on(table.userId, table.kind, table.version)
      .where(sql`${table.dogId} is null and ${table.revokedAt} is null`),
    uniqueIndex("consent_dog_standing_idx")
      .on(table.userId, table.kind, table.version, table.dogId)
      .where(sql`${table.dogId} is not null and ${table.revokedAt} is null`),
  ],
);

/*===== Logbook =====*/
// A dog's training diary (docs/app-spec.md, F14): one row per session, written by the head trainer, read by the dog's
// owner. Private by default: `is_public` only marks an entry the trainer is happy to show on the dog's public record, and
// that record exists only if its owner makes it public, which no one can until the owner approves the wording (F14).
// Entries are corrected by editing; none is deleted, so the diary is a record of what was written when.

export const logbookEntry = pgTable(
  "logbook_entry",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    dogId: uuid("dog_id")
      .notNull()
      .references(() => dog.id, { onDelete: "restrict" }),
    /** The course (enrollment) the session belongs to, when it belongs to one. */
    enrollmentId: uuid("enrollment_id").references(() => enrollment.id, { onDelete: "restrict" }),
    /** Who wrote it: the head trainer. */
    authorId: text("author_id")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    /** `YYYY-MM-DD`, Gregorian: the day of the session. */
    occurredOn: date("occurred_on", { mode: "string" }).notNull(),
    /** What was done and seen, in the trainer's words. */
    notes: text("notes").notNull(),
    /** The exercises practised, one short line each. */
    exercises: text("exercises")
      .array()
      .notNull()
      .default(sql`'{}'::text[]`),
    /** How the dog is getting on, in a sentence or two. */
    progress: text("progress"),
    /** The trainer is happy for this entry to be on the public record, if the owner makes the record public. Never the default. */
    isPublic: boolean("is_public").notNull().default(false),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [index("logbook_entry_dog_id_occurred_on_idx").on(table.dogId, table.occurredOn)],
);

/*===== Certificates =====*/
// A course-completion certificate (docs/app-spec.md, F14): a record that the Admin issues for an enrollment he has marked
// completed, one per enrollment. Its number is what a certificate's QR code and its public verification page carry. A
// certificate is never deleted; if it was issued by mistake it is revoked (the row stays, with when and why), and the
// verification page then says so.

export const certificate = pgTable("certificate", {
  id: uuid("id").primaryKey().defaultRandom(),
  /** `ZC-` and ten random hexadecimal characters, made by the database: unique, never edited. */
  number: text("number")
    .notNull()
    .unique()
    .default(sql`'ZC-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10))`),
  enrollmentId: uuid("enrollment_id")
    .notNull()
    .unique()
    .references(() => enrollment.id, { onDelete: "restrict" }),
  issuedBy: text("issued_by")
    .notNull()
    .references(() => user.id, { onDelete: "restrict" }),
  issuedAt: timestamp("issued_at").notNull().defaultNow(),
  revokedAt: timestamp("revoked_at"),
  /** Why the Admin revoked it. Private: the verification page says only that it is revoked. */
  revokedReason: text("revoked_reason"),
});

/*===== Refunds =====*/
// The ledger of money given back (docs/app-spec.md, F5). The Admin decides a refund and records it here, pays it out
// outside the app (a bank transfer), then marks it paid with the transfer's reference; a refund decided by mistake is
// cancelled before it is paid. Nothing is deleted. The sum of the refunds that stand (pending or paid) for a payment can
// never exceed what that payment charged, and the check runs under a lock on the payment, so two refunds can't both slip
// under the limit.

export const refund = pgTable(
  "refund",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    paymentId: uuid("payment_id")
      .notNull()
      .references(() => payment.id, { onDelete: "restrict" }),
    /** The item (and so the course) the refund is for, or null for the payment as a whole. Informational: the limit is the payment's. */
    paymentItemId: uuid("payment_item_id").references(() => paymentItem.id, { onDelete: "restrict" }),
    /** Rial. */
    amount: bigint("amount", { mode: "number" }).notNull(),
    /** `pending` (decided, not yet paid out), `paid` (paid out; `reference` says how) or `cancelled` (withdrawn before it was paid). */
    status: text("status").notNull().default("pending"),
    /** Why, in the Admin's words. Private to the Admin: the customer sees the amount, the state and the reference. */
    reason: text("reason").notNull(),
    /** The bank transfer's reference, written when the Admin marks it paid. */
    reference: text("reference"),
    createdBy: text("created_by")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    paidAt: timestamp("paid_at"),
    cancelledAt: timestamp("cancelled_at"),
  },
  (table) => [
    index("refund_payment_id_idx").on(table.paymentId),
    index("refund_status_created_at_idx").on(table.status, table.createdAt),
    check("refund_amount_check", sql`${table.amount} > 0`),
  ],
);

/*===== Audit Trail =====*/
// What the Admin did that touches money or a person's record, with who, what and when (docs/app-spec.md, F5 and F14). Rows
// are written and never changed or deleted. `data` holds the few facts worth keeping (an amount, a reference); it never
// holds a password, a phone number or the text of a private note.

export const auditEvent = pgTable(
  "audit_event",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    actorId: text("actor_id")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    /** e.g. `refund.created`, `refund.paid`, `refund.cancelled`, `certificate.issued`, `certificate.revoked`. */
    action: text("action").notNull(),
    /** What it was done to: `refund`, `certificate`. */
    entityType: text("entity_type").notNull(),
    entityId: text("entity_id").notNull(),
    data: jsonb("data"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (table) => [index("audit_event_entity_idx").on(table.entityType, table.entityId, table.createdAt)],
);

