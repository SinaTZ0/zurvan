/*===== Payments =====*/
// Checkout (F5): the browser-side cart becomes one pending payment listing its items, each with the price read at that
// moment. The gateway's callback settles it once and creates an enrollment per item that is still eligible.

export const payment = pgTable(
  "payment",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    customerId: text("customer_id")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    /**
     * Rial charged at the gateway now: the whole of the items' prices, or the deposit when the Admin has set one (F10).
     * What a payment "is worth" to the shop's takings; the balance, if any, is settled outside the app.
     */
    amount: bigint("amount", { mode: "number" }).notNull(),
    /** Rial: the sum of the items' prices, the full price of what was bought. Null on a payment made before deposits: it was `amount`. */
    totalAmount: bigint("total_amount", { mode: "number" }),
    /** The deposit percent in force when the payment was made (100: the whole price). */
    depositPercent: integer("deposit_percent").notNull().default(100),
    /**
     * When the customer said they are usually free, for the call that arranges the lessons: weekdays and parts of the
     * day, two independent lists in the same words as an evaluation request. A preference for coordination, never a
     * booked time; empty when they gave none.
     */
    availableDays: text("available_days")
      .array()
      .notNull()
      .default(sql`'{}'::text[]`),
    availablePeriods: text("available_periods")
      .array()
      .notNull()
      .default(sql`'{}'::text[]`),
    /** `demo` in showcase mode. */
    gateway: text("gateway").notNull(),
    /** The gateway's payment id, from starting the payment; the callback finds the payment by it. Unique (F12). */
    authority: text("authority").notNull().unique(),
    /** The gateway's tracking code after success. */
    referenceId: text("reference_id"),
    cardNumberMasked: text("card_number_masked"),
    /** `pending`, then `paid` or `failed` exactly once. Never edited after that. */
    status: text("status").notNull().default("pending"),
    failureReason: text("failure_reason"),
    paidAt: timestamp("paid_at"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    index("payment_customer_id_idx").on(table.customerId),
    index("payment_status_created_at_idx").on(table.status, table.createdAt),
    check("payment_amount_check", sql`${table.amount} > 0`),
  ],
);

